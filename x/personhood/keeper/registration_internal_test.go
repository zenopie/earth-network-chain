// TestVerifyRegistrationProof_Wired drives the fully wired keeper path — params
// verifying-key lookup -> UltraHonk verify -> nullifier extraction — against a
// real Barretenberg bb v5.0.0 proof.
//
// Uses the lean_poa fixture rather than the raw verifier oracle: the oracle's
// public inputs are [5, 8], which carry no current_date, and current_date
// pinning is now mandatory. A proof that cannot name a date is not a
// registration proof.
func TestVerifyRegistrationProof_Wired(t *testing.T) {
	vk := readFileAt(t, filepath.Join(leanDir, "vk"))
	proof := readFileAt(t, filepath.Join(leanDir, "proof"))

	// public_inputs file is concatenated 32-byte big-endian field elements;
	// present them as decimal signals, the wire form MsgRegister carries.
	pub := readFileAt(t, filepath.Join(leanDir, "public_inputs"))
	var signals []string
	for i := 0; i+32 <= len(pub); i += 32 {
		signals = append(signals, new(big.Int).SetBytes(pub[i:i+32]).String())
	}

	const algo = "lean_poa"
	k, baseCtx := newKeeperForTest(t)
	ctx := sdk.UnwrapSDKContext(baseCtx).WithBlockTime(time.Date(2025, 1, 1, 12, 0, 0, 0, time.UTC))
	if err := k.Params.Set(ctx, types.Params{
		VerifyingKeys:               map[string][]byte{algo: vk},
		RegistrationValiditySeconds: types.DefaultRegistrationValiditySeconds,
		NullifierIndex:              1,
		DscKeyIndex:                 2,
		CurrentDateIndex:            0,
		CurrentDateMaxSkewSeconds:   types.DefaultCurrentDateMaxSkewSeconds,
	}); err != nil {
		t.Fatalf("set params: %v", err)
	}

	// Valid proof -> nullifier == public signal[NullifierIndex].
	nullifier, _, err := k.verifyRegistrationProof(ctx, proof, signals, algo, nil)
	if err != nil {
		t.Fatalf("verifyRegistrationProof: %v", err)
	}
	want, err := signalToBytes32(signals[1])
	if err != nil {
		t.Fatal(err)
	}
	if !bytes.Equal(nullifier, want) {
		t.Fatalf("nullifier = %x, want %x", nullifier, want)
	}
	t.Log("valid UltraHonk registration proof verified; nullifier extracted")

	// Unknown algorithm -> ErrNoVerifyingKey.
	if _, _, err := k.verifyRegistrationProof(ctx, proof, signals, "nope", nil); err == nil {
		t.Fatal("expected error for unknown algorithm")
	}

	// Tampered public signal -> proof invalid.
	bad := append([]string(nil), signals...)
	bad[1] = incLastDigit(bad[1])
	if _, _, err := k.verifyRegistrationProof(ctx, proof, bad, algo, nil); err == nil {
		t.Fatal("expected error for tampered public signal")
	}
}

// TestSignalToBytes32_RejectsNonCanonical pins the canonicality check on public
// signals. The BN254 prime is just under 2^254, so n and n+p name the same field
// element and verify against the same proof, but produce different 32-byte
// nullifiers. Accepting both would let one passport register more than once.
func TestSignalToBytes32_RejectsNonCanonical(t *testing.T) {
	p := fr.Modulus()

	// A canonical signal round-trips to its big-endian bytes.
	got, err := signalToBytes32("250101")
	if err != nil {
		t.Fatalf("canonical signal rejected: %v", err)
	}
	var want [32]byte
	big.NewInt(250101).FillBytes(want[:])
	if !bytes.Equal(got, want[:]) {
		t.Fatalf("signalToBytes32(250101) = %x, want %x", got, want)
	}

	// The prime itself, and n+p for a small n, are the same field elements as 0
	// and n — and must not be accepted as distinct signals.
	for _, s := range []string{
		p.String(),
		new(big.Int).Add(p, big.NewInt(250101)).String(),
		new(big.Int).Sub(new(big.Int).Lsh(big.NewInt(1), 256), big.NewInt(1)).String(),
	} {
		if _, err := signalToBytes32(s); err == nil {
			t.Fatalf("non-canonical signal %s was accepted", s)
		}
	}
}

// leanDir points at a real lean_poa proof whose public inputs are
// [current_date=250101, nullifier, dsc_key].
const leanDir = "testdata/lean_poa"

// TestVerifyRegistrationProof_CurrentDatePinning drives the current_date
// freshness check against a real lean_poa proof: the circuit already proved
// expiry >= current_date, and the chain must pin current_date (public input 0,
// value 250101 = 2025-01-01) to the block time so an expired passport cannot be
// registered by backdating current_date.
func TestVerifyRegistrationProof_CurrentDatePinning(t *testing.T) {
	vk := readFileAt(t, filepath.Join(leanDir, "vk"))
	proof := readFileAt(t, filepath.Join(leanDir, "proof"))
	pub := readFileAt(t, filepath.Join(leanDir, "public_inputs"))
	var signals []string
	for i := 0; i+32 <= len(pub); i += 32 {
		signals = append(signals, new(big.Int).SetBytes(pub[i:i+32]).String())
	}
	if len(signals) != 3 || signals[0] != "250101" {
		t.Fatalf("unexpected lean_poa public inputs: %v", signals)
	}

	const algo = "lean_poa"
	params := types.Params{
		VerifyingKeys:               map[string][]byte{algo: vk},
		RegistrationValiditySeconds: types.DefaultRegistrationValiditySeconds,
		NullifierIndex:              1,
		DscKeyIndex:                 2,
		CurrentDateIndex:            0,
		CurrentDateMaxSkewSeconds:   2 * 24 * 60 * 60, // 2 days
	}

	k, baseCtx := newKeeperForTest(t)
	sdkCtx := sdk.UnwrapSDKContext(baseCtx)

	// Block time within skew of current_date (2025-01-01) -> accepted.
	ctxOK := sdkCtx.WithBlockTime(time.Date(2025, 1, 1, 12, 0, 0, 0, time.UTC))
	if err := k.Params.Set(ctxOK, params); err != nil {
		t.Fatalf("set params: %v", err)
	}
	nullifier, _, err := k.verifyRegistrationProof(ctxOK, proof, signals, algo, nil)
	if err != nil {
		t.Fatalf("in-skew proof rejected: %v", err)
	}
	wantNull, _ := signalToBytes32(signals[1])
	if !bytes.Equal(nullifier, wantNull) {
		t.Fatalf("nullifier = %x, want %x (signal[1])", nullifier, wantNull)
	}
	t.Log("lean_poa proof verified and current_date pinned to block time; nullifier from index 1")

	// Block time far from current_date (31 days) -> rejected as stale.
	ctxStale := sdkCtx.WithBlockTime(time.Date(2025, 2, 1, 0, 0, 0, 0, time.UTC))
	if err := k.Params.Set(ctxStale, params); err != nil {
		t.Fatalf("set params (stale): %v", err)
	}
	if _, _, err := k.verifyRegistrationProof(ctxStale, proof, signals, algo, nil); err == nil {
		t.Fatal("expected rejection: current_date far from block time")
	}

	// Zero skew -> rejected, not waved through. A zero here used to skip the
	// check entirely, which made the most restrictive-looking setting the one
	// that let every backdated proof in. Registration now fails closed until
	// governance sets a real tolerance.
	params.CurrentDateMaxSkewSeconds = 0
	if err := k.Params.Set(ctxOK, params); err != nil {
		t.Fatalf("set params (unset skew): %v", err)
	}
	if _, _, err := k.verifyRegistrationProof(ctxOK, proof, signals, algo, nil); err == nil {
		t.Fatal("expected rejection: zero skew must disable registration, not the check")
	}
}

func TestYYMMDDToUnix(t *testing.T) {
	f := func(yymmdd int64) []byte {
		var buf [32]byte
		new(big.Int).SetInt64(yymmdd).FillBytes(buf[:])
		return buf[:]
	}
	got, err := yymmddToUnix(f(250101))
	if err != nil {
		t.Fatal(err)
	}
	if want := time.Date(2025, 1, 1, 0, 0, 0, 0, time.UTC).Unix(); got != want {
		t.Fatalf("250101 -> %d, want %d", got, want)
	}
	for _, bad := range []int64{251301 /*month 13*/, 250132 /*day 32*/, 250100 /*day 0*/, 1000000 /*too big*/} {
		if _, err := yymmddToUnix(f(bad)); err == nil {
			t.Fatalf("expected error for %d", bad)
		}
	}
}

