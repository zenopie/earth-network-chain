func readFileAt(t *testing.T, path string) []byte {
	t.Helper()
	b, err := os.ReadFile(path)
	if err != nil {
		t.Skipf("fixture %s missing (%v)", path, err)
	}
	return b
}

func incLastDigit(s string) string {
	b := []byte(s)
	i := len(b) - 1
	if b[i] == '9' {
		b[i] = '0'
	} else {
		b[i]++
	}
	return string(b)
}
