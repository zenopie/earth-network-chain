// Command privacyfixtures writes a Prover.toml for the membership or transfer
// circuit (earth-network-mobile/circuits) from trees and derivations built with
// zk/merkle and zk/privacy, plus the public inputs the chain would supply
// (public_inputs.expected, 32-byte big-endian fields in ABI order). Running
// nargo execute on the toml is the Go<->Noir parity check: the circuit only
// accepts if every hash, path and derivation agrees.
//
//	go run ./tools/privacyfixtures <membership|membership-zeroed|transfer|note_vote> <outdir>
//	go run ./tools/privacyfixtures shielded <outdir>
//	go run ./tools/privacyfixtures passport <name>
//
// passport prints "address doc date" for x/personhood/testutil's registration
// <name>, the arguments tools/poafixtures binds its passport proof with.
//
// membership-zeroed builds the same witness after the chain zeroed the leaf;
// the circuit must reject it. shielded writes one <outdir>/<transfer>/ per
// transfer in x/shielded/testutil's scenario, which the app tests replay on a
// real chain (scripts/shielded-fixtures.sh proves them).
package main

import (
	"fmt"
	"os"
	"path/filepath"
	"strings"

	"github.com/consensys/gnark-crypto/ecc/bn254/fr"

	personhoodtest "github.com/earth-network/earth/x/personhood/testutil"
	shieldedtest "github.com/earth-network/earth/x/shielded/testutil"
	"github.com/earth-network/earth/zk/merkle"
	"github.com/earth-network/earth/zk/privacy"
)

// det is a deterministic pseudo-random field element, so fixtures are stable.
func det(label string, i uint64) fr.Element {
	return privacy.H(privacy.AssetID("fixture/"+label), privacy.U64(i))
}

func hex(e fr.Element) string {
	b := e.Bytes()
	return fmt.Sprintf("0x%x", b[:])
}

func q(e fr.Element) string { return fmt.Sprintf("%q", hex(e)) }

func arr(es []fr.Element) string {
	parts := make([]string, len(es))
	for i, e := range es {
		parts[i] = q(e)
	}
	return "[" + strings.Join(parts, ", ") + "]"
}

func main() {
	if len(os.Args) == 3 && os.Args[1] == "passport" {
		r, ok := personhoodtest.Registrations[os.Args[2]]
		if !ok {
			fmt.Fprintf(os.Stderr, "unknown registration %q\n", os.Args[2])
			os.Exit(2)
		}
		b := r.Binding()
		fmt.Printf("address=%s doc=%s date=%s\n", b.String(), r.Doc, r.Date)
		return
	}
	if len(os.Args) != 3 {
		fmt.Fprintln(os.Stderr, "usage: privacyfixtures <membership|membership-zeroed|transfer|note_vote|shielded> <outdir>")
		os.Exit(2)
	}
	out := os.Args[2]
	if err := os.MkdirAll(out, 0o755); err != nil {
		panic(err)
	}
	if os.Args[1] == "shielded" {
		s := shieldedtest.Default()
		for i, sp := range s.Transfers {
			toml, pub, err := s.Witness(i)
			must(err)
			writeFixture(filepath.Join(out, sp.Name), toml, pub)
		}
		return
	}
	var toml string
	var pub []fr.Element
	switch os.Args[1] {
	case "membership":
		toml, pub = membership(false)
	case "membership-zeroed":
		toml, pub = membership(true)
	case "transfer":
		toml, pub = transfer()
	case "note_vote":
		toml, pub = noteVote()
	default:
		fmt.Fprintf(os.Stderr, "unknown circuit %q\n", os.Args[1])
		os.Exit(2)
	}
	writeFixture(out, toml, pub)
}

func writeFixture(dir, toml string, pub []fr.Element) {
	must(os.MkdirAll(dir, 0o755))
	must(os.WriteFile(filepath.Join(dir, "Prover.toml"), []byte(toml), 0o644))
	var raw []byte
	for _, e := range pub {
		b := e.Bytes()
		raw = append(raw, b[:]...)
	}
	must(os.WriteFile(filepath.Join(dir, "public_inputs.expected"), raw, 0o644))
}

func mustEl(e fr.Element, err error) fr.Element {
	must(err)
	return e
}

func must(err error) {
	if err != nil {
		panic(err)
	}
}

func membership(zeroed bool) (string, []fr.Element) {
	t := merkle.NewMem()
	const ours = 13
	idSecret := det("id_secret", 0)
	dscKey := det("dsc", 0)
	country := privacy.CountryField("DE")
	const activatedAt = uint64(1_790_000_000)
	for i := uint64(0); i < 21; i++ {
		leaf := privacy.IdentityLeaf(privacy.IDC(det("other", i)), det("dsc", i%3), privacy.CountryField([]string{"DE", "FR", ""}[i%3]), 1_780_000_000+i)
		if i == ours {
			leaf = privacy.IdentityLeaf(privacy.IDC(idSecret), dscKey, country, activatedAt)
		}
		_, err := t.Append(leaf)
		must(err)
	}
	must(t.Update(3, fr.Element{})) // an expired registration elsewhere
	if zeroed {
		must(t.Update(ours, fr.Element{}))
	}
	// the path is taken before zeroing in the negative case: a stale path
	// against the post-zeroing root must fail.
	t2 := merkle.NewMem()
	for i := uint64(0); i < t.Size(); i++ {
		_, _ = t2.Append(mustEl(t.Leaf(i)))
	}
	if zeroed {
		must(t2.Update(ours, privacy.IdentityLeaf(privacy.IDC(idSecret), dscKey, country, activatedAt)))
	}
	sib, err := t2.Path(ours)
	must(err)

	root := mustEl(t.Root())
	scope := privacy.AssetID("claim:20360")
	nullifier := privacy.ScopeNullifier(idSecret, scope)
	signal := det("signal", 0)
	excluded := det("dsc", 99)
	excludedCountry := privacy.CountryField("FR")
	maxAct := privacy.U64(activatedAt + 86_400)

	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by tools/privacyfixtures. Do not edit.\n")
	fmt.Fprintf(&b, "id_secret = %s\ndsc_key = %s\ncountry = %s\nactivated_at = \"%d\"\nleaf_index = \"%d\"\n",
		q(idSecret), q(dscKey), q(country), activatedAt, ours)
	fmt.Fprintf(&b, "siblings = %s\n", arr(sib[:]))
	fmt.Fprintf(&b, "root = %s\nscope = %s\nnullifier = %s\nsignal = %s\nexcluded_dsc = %s\nexcluded_country = %s\nmax_activation = \"%d\"\n",
		q(root), q(scope), q(nullifier), q(signal), q(excluded), q(excludedCountry), activatedAt+86_400)
	return b.String(), []fr.Element{root, scope, nullifier, signal, excluded, excludedCountry, maxAct}
}

func transfer() (string, []fr.Element) {
	t := merkle.NewMem()
	nk := det("nk", 0)
	opk := privacy.OwnerPK(nk)
	assetA := privacy.AssetID("uanml")
	erth := privacy.AssetID("uerth")
	inVal := [3]uint64{700_000, 300_000, 50_000}
	outVal := [3]uint64{600_000, 350_000, 40_000}
	const fee, vPubOut = uint64(10_000), uint64(50_000)
	assets := [3]fr.Element{assetA, assetA, erth}
	positions := [3]uint64{4, 7, 9}
	var rho, rcm [3]fr.Element
	for i := range 3 {
		rho[i], rcm[i] = det("rho", uint64(i)), det("rcm", uint64(i))
	}
	next := 0
	for p := uint64(0); p < 12; p++ {
		cm := privacy.CM(erth, p+1, det("otherpc", p))
		if next < 3 && p == positions[next] {
			cm = privacy.CM(assets[next], inVal[next], privacy.PC(opk, rho[next], rcm[next]))
			next++
		}
		_, err := t.Append(cm)
		must(err)
	}
	root := mustEl(t.Root())

	var paths [3]string
	var nf, cmOut, outPC [3]fr.Element
	for i := range 3 {
		sib, err := t.Path(positions[i])
		must(err)
		paths[i] = arr(sib[:])
		nf[i] = privacy.NF(nk, rho[i], uint32(positions[i]))
		outPC[i] = privacy.PC(privacy.OwnerPK(det("recipient", uint64(i))), det("orho", uint64(i)), det("orcm", uint64(i)))
		cmOut[i] = privacy.CM(assets[i], outVal[i], outPC[i])
	}
	signal := det("signal", 1)

	u := func(v [3]uint64) string {
		return fmt.Sprintf("[\"%d\", \"%d\", \"%d\"]", v[0], v[1], v[2])
	}
	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by tools/privacyfixtures. Do not edit.\n")
	fmt.Fprintf(&b, "asset = %s\nnk = %s\n", q(assetA), q(nk))
	fmt.Fprintf(&b, "in_value = %s\nin_rho = %s\nin_rcm = %s\nin_pos = %s\n",
		u(inVal), arr(rho[:]), arr(rcm[:]), u(positions))
	fmt.Fprintf(&b, "in_path = [%s]\n", strings.Join(paths[:], ", "))
	fmt.Fprintf(&b, "out_value = %s\nout_pc = %s\n", u(outVal), arr(outPC[:]))
	fmt.Fprintf(&b, "root = %s\nnf = %s\ncm_out = %s\nfee = \"%d\"\nv_pub_out = \"%d\"\nasset_pub = %s\nsignal = %s\n",
		q(root), arr(nf[:]), arr(cmOut[:]), fee, vPubOut, q(assetA), q(signal))

	pub := []fr.Element{root}
	pub = append(pub, nf[:]...)
	pub = append(pub, cmOut[:]...)
	pub = append(pub, privacy.U64(fee), privacy.U64(vPubOut), assetA, signal)
	return b.String(), pub
}

// noteVote is a derth note voting on proposal 42 from the middle of a tree.
func noteVote() (string, []fr.Element) {
	t := merkle.NewMem()
	nk := det("nk", 5)
	rho, rcm := det("vrho", 0), det("vrcm", 0)
	asset := privacy.AssetID("derth/earthvaloper1qqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqqq")
	const value, pos, proposal = uint64(12_345_678), uint64(6), uint64(42)
	for p := uint64(0); p < 10; p++ {
		cm := privacy.CM(asset, p+1, det("otherpc", p))
		if p == pos {
			cm = privacy.CM(asset, value, privacy.PC(privacy.OwnerPK(nk), rho, rcm))
		}
		_, err := t.Append(cm)
		must(err)
	}
	root := mustEl(t.Root())
	sib, err := t.Path(pos)
	must(err)
	voteNF := privacy.VoteNF(nk, rho, uint32(pos), proposal)
	nf := privacy.NF(nk, rho, uint32(pos))
	signal := det("signal", 2)

	var b strings.Builder
	fmt.Fprintf(&b, "# Generated by tools/privacyfixtures. Do not edit.\n")
	fmt.Fprintf(&b, "nk = %s\nrho = %s\nrcm = %s\nposition = \"%d\"\npath = %s\n", q(nk), q(rho), q(rcm), pos, arr(sib[:]))
	fmt.Fprintf(&b, "root = %s\nasset = %s\nvalue = \"%d\"\nproposal_id = \"%d\"\nvote_nf = %s\nnf = %s\nsignal = %s\n",
		q(root), q(asset), value, proposal, q(voteNF), q(nf), q(signal))
	return b.String(), []fr.Element{root, asset, privacy.U64(value), privacy.U64(proposal), voteNF, nf, signal}
}
